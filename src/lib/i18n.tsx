const DICTS: Record<Lang, Dict> = { ar, en, fr, ur };

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  dir: "rtl" | "ltr";
}

const Ctx = createContext<I18nCtx>({
  lang: "ar",
  setLang: () => {},
  t: (k) => k,
  dir: "rtl",
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const saved =
      (typeof window !== "undefined" &&
        (localStorage.getItem("app_lang") as Lang)) || null;
    if (saved && DICTS[saved]) {
      const id = requestAnimationFrame(() => setLangState(saved));
      return () => cancelAnimationFrame(id);
    }
  }, []);

  useEffect(() => {
    const isRtl = RTL_LANGS.includes(lang);
    if (typeof document !== "undefined") {
      document.documentElement.dir = isRtl ? "rtl" : "ltr";
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("app_lang", l);
    } catch {}
  }, []);

  const t = useCallback(
    (key: string) => DICTS[lang]?.[key] ?? DICTS.en?.[key] ?? key,
    [lang]
  );

  const dir: "rtl" | "ltr" = RTL_LANGS.includes(lang) ? "rtl" : "ltr";

  return <Ctx.Provider value={{ lang, setLang, t, dir }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}

